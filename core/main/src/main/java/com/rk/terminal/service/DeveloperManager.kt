    fun getStoredKey(context: Context, key: String): String {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        return prefs.getString(key, "") ?: ""
    }

    fun saveStoredKey(context: Context, key: String, value: String) {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        prefs.edit().putString(key, value.trim()).apply()
    }

    /**
     * Synchronizes API keys to the Alpine rootfs environment.
     * Writes to /etc/profile.d/ai_keys.sh, ~/.profile, and ~/.bashrc
     */
    suspend fun syncKeysToAlpine(context: Context): Boolean = withContext(Dispatchers.IO) {
        try {
            val keys = mapOf(
                KEY_ANTHROPIC to getStoredKey(context, KEY_ANTHROPIC),
                KEY_OPENAI to getStoredKey(context, KEY_OPENAI),
                KEY_GEMINI to getStoredKey(context, KEY_GEMINI),
                KEY_DEEPSEEK to getStoredKey(context, KEY_DEEPSEEK),
                KEY_GROQ to getStoredKey(context, KEY_GROQ),
                KEY_BASE_URL to getStoredKey(context, KEY_BASE_URL)
            )

            val alpineRoot = File(context.filesDir.parentFile, "local/alpine")
            if (!alpineRoot.exists()) {
                return@withContext false
            }

            val profileD = File(alpineRoot, "etc/profile.d")
            profileD.mkdirs()

            val aiKeysFile = File(profileD, "ai_keys.sh")
            val sb = StringBuilder()
            sb.append("#!/bin/sh\n")
            sb.append("# Generated by AndLinux AI Studio\n")

            keys.forEach { (key, value) ->
                if (value.isNotEmpty()) {
                    sb.append("export $key='$value'\n")
                }
            }

            aiKeysFile.writeText(sb.toString())
            aiKeysFile.setReadable(true, false)
            aiKeysFile.setExecutable(true, false)

            // Also append or write to root .profile
            val rootDir = File(alpineRoot, "root")
            rootDir.mkdirs()
            val bashrc = File(rootDir, ".bashrc")
            val bashrcContent = if (bashrc.exists()) bashrc.readText() else ""
            val marker = "# ANDLINUX_AI_KEYS_MARKER"
            val newBlock = "\n$marker\n[ -f /etc/profile.d/ai_keys.sh ] && . /etc/profile.d/ai_keys.sh\n"

            if (!bashrcContent.contains(marker)) {
                bashrc.appendText(newBlock)
            }

            true
        } catch (e: Exception) {
            e.printStackTrace()
            false
        }
    }

    /**
     * Executes a command inside the Alpine Linux environment using the active session.
     */
    fun sendCommandToAlpine(mainActivity: MainActivity, command: String): Boolean {
        val binder = mainActivity.sessionBinder ?: return false
        val opencodeSession = binder.getSession("opencode")
        val mainSession = binder.getSession("main")

        val targetSession = mainSession ?: opencodeSession
        return if (targetSession != null) {
            targetSession.write(command + "\n")
            true
        } else {
            false
        }
    }

    /**
     * Triggers installation of an apk package group in Alpine.
     */
    fun installPackages(mainActivity: MainActivity, packages: String): Boolean {
        val cmd = "apk update && apk add $packages"
        return sendCommandToAlpine(mainActivity, cmd)
    }

    /**
     * Checks if a local port is currently open and accepting connections.
     */
    suspend fun isPortOpen(port: Int): Boolean = withContext(Dispatchers.IO) {
        try {
            Socket().use { socket ->
                socket.connect(InetSocketAddress("127.0.0.1", port), 400)
                true
            }
        } catch (_: Exception) {
            false
        }
    }

    /**
     * Launches external browser for a local port or URL.
     */
    fun openInExternalBrowser(context: Context, url: String) {
        try {
            val intent = Intent(Intent.ACTION_VIEW, Uri.parse(url)).apply {
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            context.startActivity(intent)
        } catch (e: Exception) {
            Toast.makeText(context, "Could not open browser: ${e.message}", Toast.LENGTH_SHORT).show()
        }
    }

    /**
     * Restarts OpenCode web server in background.
     */
    fun restartOpenCodeServer(mainActivity: MainActivity) {
        val cmd = "for pid in \$(ps | awk '/[o]pencode/ {print \$1}'); do kill -9 \"\$pid\" 2>/dev/null; done; sleep 1; touch /tmp/opencode_ready; OPENCODE_SERVER_PASSWORD='andlinux-local-opencode' nohup opencode web --port 4123 --hostname 127.0.0.1 >/tmp/opencode.log 2>&1 &"
        sendCommandToAlpine(mainActivity, cmd)
    }
